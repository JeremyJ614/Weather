/**
 * Model viewer parameters, ported from the VIP renderer (scripts/render_maps.py): every
 * field's GRIB index match, units, contour levels and color scale. Colors are editable in
 * admin as `model:<scale>:<step>`. Regenerate by hand from VIP if its tables change.
 */
export type Param = {
  key: string;
  label: string;
  group: string;
  /** Substring of the .idx line for the record (and `also`, when the threshold is apart). */
  match: string;
  also?: string;
  extra?: string[];
  combine?: "mag" | "vecdiff" | "thetae" | "lapse";
  unit: string;
  cmap: string;
  levels: number[];
  /** True when values under the first level still mean something (no transparency). */
  full?: boolean;
};

