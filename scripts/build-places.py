"""Builds src/lib/geo/places.data.ts from public-domain Census files:
the place Gazetteer (names, coordinates) and city population estimates.
Usage: python3 -I scripts/build-places.py <Gaz_place_national.zip> <sub-est.csv>
"""
import csv, re, sys, zipfile

gz, sub = sys.argv[1], sys.argv[2]
pop = {}
with open(sub, encoding="latin-1") as f:
    for r in csv.DictReader(f):
        if r["SUMLEV"] in ("162", "170", "172"):
            pop[r["STATE"] + r["PLACE"]] = int(r["POPESTIMATE2024"] or 0)

SUFFIX = re.compile(
    r"\s+(CDP|city|town|village|borough|comunidad|zona urbana|municipality|"
    r"unified government|metropolitan government|consolidated government|"
    r"urban county|corporation|city and borough|(and )?borough)(\s*\(balance\))?$|\s*\(balance\)$"
)
z = zipfile.ZipFile(gz)
rows = z.read(z.namelist()[0]).decode("utf-8").splitlines()[1:]
out = {}
for line in rows:
    c = [x.strip() for x in line.split("\t")]
    st, geoid, name, lat, lon = c[0], c[1], c[3], float(c[10]), float(c[11])
    if st == "PR":
        continue
    clean = SUFFIX.sub("", name).strip()
    clean = re.sub(r"\s*\(.*?\)$", "", clean)
    clean = re.sub(r"^Urban (Honolulu)$", r"\1", clean)
    clean = re.sub(r"-(Davidson|Fayette|Jefferson|Richmond|Clarke|Athens).*$", "", clean)
    clean = re.sub(r"(/|-|, )[A-Z][\w .]* County.*$", "", clean)
    clean = {"Boise City": "Boise"}.get(clean, clean) if st == "ID" else clean
    p = pop.get(geoid, 0)
    key = (clean.lower(), st)
    if key in out and out[key][3] >= p:
        continue
    out[key] = (clean, st, f"{lat:.3f}|{lon:.3f}", p)

lines = sorted(out.values(), key=lambda r: -r[3])
body = "".join(f"{n}|{st}|{ll}|{p}\\n" for n, st, ll, p in lines)
with open("src/lib/geo/places.data.ts", "w") as f:
    f.write("// Generated by scripts/build-places.py from public-domain Census data. Do not edit.\n")
    f.write("// name|state|lat|lon|population, most populous first.\n")
    f.write(f'export const PLACES = "{body}";\n')
print(len(lines))
